-- ── Seed: the three factory breaks, attached by containment ─────────────────
-- A shift's current default window comes from its open V50 default period
-- (falling back to the shifts row). The break lands on the shift whose window
-- CONTAINS the break's start, counting across midnight; each shift takes at
-- most one break, the earliest-listed matching window.

WITH current_windows AS (
    SELECT s.id AS shift_id,
           COALESCE(p.start_time, s.start_time) AS win_start,
           COALESCE(p.end_time,   s.end_time)   AS win_end
    FROM shifts s
    LEFT JOIN employee_shift_time_periods p
           ON p.shift_id = s.id
          AND p.employee_id IS NULL
          AND p.archived_at IS NULL
          AND p.valid_to IS NULL
    WHERE s.is_active = true
      AND s.archived_at IS NULL
),
candidate AS (
    SELECT w.shift_id, b.break_start, b.break_end, b.ord
    FROM current_windows w
    JOIN (VALUES
            (TIME '11:00', TIME '11:30', 1),
            (TIME '19:00', TIME '19:30', 2),
            (TIME '02:00', TIME '02:30', 3)
         ) AS b(break_start, break_end, ord)
      ON CASE
           WHEN w.win_start < w.win_end
                THEN b.break_start >= w.win_start AND b.break_start < w.win_end
           ELSE b.break_start >= w.win_start OR  b.break_start < w.win_end
         END
),
one_per_shift AS (
    SELECT DISTINCT ON (shift_id) shift_id, break_start, break_end
    FROM candidate
    ORDER BY shift_id, ord
)
INSERT INTO employee_shift_break_periods (shift_id, start_time, end_time, valid_from, note)
SELECT o.shift_id, o.break_start, o.break_end, DATE '1970-01-01',
       'Podrazumevana pauza smene, postavljena pri uvođenju pauza.'
FROM one_per_shift o
WHERE NOT EXISTS (
    SELECT 1 FROM employee_shift_break_periods e
    WHERE e.shift_id = o.shift_id AND e.employee_id IS NULL
);

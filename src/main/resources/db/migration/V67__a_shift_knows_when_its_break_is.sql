-- =============================================================================
-- A shift knows when its break is
-- =============================================================================
-- WHAT CHANGES
--   One new table, employee_shift_break_periods: WHEN the pauza falls inside a
--   given shift — for one employee, or by default for everybody. The exact
--   sibling of employee_shift_time_periods (V50), same shape, same reading:
--
--     employee_id set   → this employee's own break window for that shift.
--     employee_id NULL  → the shift's DEFAULT break window, versioned.
--     Resolution on a date: the employee's row covering the date wins; then
--     the default row; then THERE IS NO BREAK — unlike shift times there is
--     no third fallback, because a shift without a configured break simply
--     has none to draw.
--
-- WHAT READS IT
--   ShiftBreakResolver — the one answer to "when is this person's pauza on
--   this date". BreakLogWriter turns that answer into the karton row: a work
--   log on the standalone operation "Pauza" (V65 made such operations
--   possible; the operation itself is administered in the UI, not seeded
--   here). The log's category is the operation's own; the category pairs /
--   mappings the recalculation already applies derive the effective one, so
--   nothing here decides pay.
--
-- WHAT THIS DOES NOT TOUCH
--   work_shifts rows and their logs stay the material truth. A moved break
--   window reaches only logs written AFTER the move; nothing historical is
--   rewritten.
--
-- SEED
--   The three given defaults — 11:00–11:30, 19:00–19:30, 02:00–02:30 — are
--   attached to the active shifts whose CURRENT default window contains the
--   break's start (overnight-aware), one break per shift, first matching
--   window wins. A shift the rule does not reach gets its default through the
--   šifarnik instead; a wrongly matched one is corrected the same way. Dated
--   from 1970 for the same reason V50's seed is: the default must cover every
--   date the app can be asked about.
--
--   Guarded; replaying is safe.
--
--   · Rollback: DROP TABLE employee_shift_break_periods;
--       DELETE FROM audit_tables WHERE table_name = 'employee_shift_break_periods';
-- =============================================================================

CREATE TABLE employee_shift_break_periods (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL = the shift's default break, a real employee = that person's own.
    employee_id bigint REFERENCES employees (id),
    shift_id    bigint NOT NULL REFERENCES shifts (id),
    start_time  time   NOT NULL,
    end_time    time   NOT NULL,
    valid_from  date   NOT NULL,
    valid_to    date,
    note        varchar(255),
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    archived_at timestamptz,
    archived_by bigint REFERENCES users (id),
    -- end < start is legal (a break across midnight, shift III); equal is not.
    CONSTRAINT chk_esbp_times_differ CHECK (start_time <> end_time),
    CONSTRAINT chk_esbp_range CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

COMMENT ON TABLE employee_shift_break_periods IS
    'When the pauza falls inside a shift, dated: employee_id set = that person''s own window, employee_id NULL = the shift''s default (versioned). Read by ShiftBreakResolver; turned into a karton log on the standalone operation "Pauza" only when asked.';
COMMENT ON COLUMN employee_shift_break_periods.employee_id IS
    'NULL = the default row for the shift; set = this employee''s override of it.';
COMMENT ON COLUMN employee_shift_break_periods.valid_to IS
    'Inclusive, like every other period here. NULL = still in force.';

-- One break in force at a time, per (shift, employee-or-default) — the same
-- guard V50 uses; btree_gist is in the baseline.
ALTER TABLE employee_shift_break_periods
    ADD CONSTRAINT ex_esbp_no_overlap EXCLUDE USING gist (
        shift_id WITH =,
        COALESCE(employee_id, ('-1'::integer)::bigint) WITH =,
        daterange(valid_from,
                  CASE WHEN valid_to IS NULL THEN NULL::date ELSE (valid_to + 1) END)
            WITH &&
    ) WHERE (archived_at IS NULL);

CREATE INDEX idx_esbp_lookup
    ON employee_shift_break_periods (shift_id, employee_id, valid_from)
    WHERE archived_at IS NULL;
CREATE INDEX idx_esbp_employee
    ON employee_shift_break_periods (employee_id)
    WHERE archived_at IS NULL;

CREATE TRIGGER trg_03_esbp_updated_at
    BEFORE UPDATE ON employee_shift_break_periods
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


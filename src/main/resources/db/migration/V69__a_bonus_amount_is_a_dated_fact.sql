-- =============================================================================
-- A bonus amount is a dated fact
-- =============================================================================
-- WHAT CHANGES
--   One new table, bonus_category_amount_periods: HOW MUCH a bonus category
--   pays, as dated spells — the same shape employee_shift_time_periods (V50)
--   and employee_shift_break_periods (V67) gave the shifts. Until now the
--   amount lived only in bonus_categories.bonus_amount and was edited IN
--   PLACE, so raising a bonus silently changed what any later recalculation
--   of an older, unlocked month would pay.
--
--     valid_to IS NULL → the amount in force today.
--     Resolution on a date: the category's period covering the date; a month
--     before the first period (cannot happen after the seed below) falls back
--     to bonus_categories.bonus_amount in code.
--
-- WHAT READS IT
--   MonthlyBonusCalculator.baseBonus — the base of the monthly bonus becomes
--   "the category's amount in force on the payroll month", not "the amount
--   right now". bonus_categories.bonus_amount STAYS, as the mirror of the
--   open period: lists and pickers keep reading it, no calculator does.
--
-- WHAT THIS DOES NOT TOUCH
--   Locked payroll runs are frozen documents and never recompute. The tier
--   bonus (bonus_eligibility_rules) is already month-keyed and unchanged.
--
-- SEED
--   One OPEN period per existing category (archived ones too — a historical
--   month may still be recalculated), carrying today's bonus_amount, dated
--   from 1970 for the same reason the V50/V67 seeds are: the amount must
--   cover every month the app can be asked about. Guarded; replaying is safe.
--
--   · Rollback: DROP TABLE bonus_category_amount_periods;
--       DELETE FROM audit_tables WHERE table_name = 'bonus_category_amount_periods';
-- =============================================================================

CREATE TABLE bonus_category_amount_periods (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bonus_category_id bigint NOT NULL REFERENCES bonus_categories (id),
    amount            numeric(10, 2) NOT NULL,
    valid_from        date NOT NULL,
    valid_to          date,
    note              varchar(255),
    created_by        bigint REFERENCES users (id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz,
    archived_at       timestamptz,
    archived_by       bigint REFERENCES users (id),
    CONSTRAINT chk_bcap_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_bcap_range CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

COMMENT ON TABLE bonus_category_amount_periods IS
    'How much a bonus category pays, dated: one spell per amount, valid_to NULL = in force. Read by MonthlyBonusCalculator for the payroll month; bonus_categories.bonus_amount mirrors the open spell for lists only.';
COMMENT ON COLUMN bonus_category_amount_periods.valid_to IS
    'Inclusive, like every other period here. NULL = still in force.';

-- One amount in force at a time per category — the V50/V67 guard;
-- btree_gist is in the baseline.
ALTER TABLE bonus_category_amount_periods
    ADD CONSTRAINT ex_bcap_no_overlap EXCLUDE USING gist (
        bonus_category_id WITH =,
        daterange(valid_from,
                  CASE WHEN valid_to IS NULL THEN NULL::date ELSE (valid_to + 1) END)
            WITH &&
    ) WHERE (archived_at IS NULL);

CREATE INDEX idx_bcap_lookup
    ON bonus_category_amount_periods (bonus_category_id, valid_from)
    WHERE archived_at IS NULL;

CREATE TRIGGER trg_03_bcap_updated_at
    BEFORE UPDATE ON bonus_category_amount_periods
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ── Auditing ─────────────────────────────────────────────────────────────────

INSERT INTO public.audit_tables (table_name)
SELECT 'bonus_category_amount_periods'
WHERE NOT EXISTS (
    SELECT 1 FROM public.audit_tables WHERE table_name = 'bonus_category_amount_periods'
);

DROP TRIGGER IF EXISTS trg_audit_logs_bonus_category_amount_periods
    ON public.bonus_category_amount_periods;
CREATE TRIGGER trg_audit_logs_bonus_category_amount_periods
    AFTER INSERT OR DELETE OR UPDATE ON public.bonus_category_amount_periods
    FOR EACH ROW EXECUTE FUNCTION public.audit_trigger_fn();

-- ── Seed: today's amounts become the open spells ─────────────────────────────

INSERT INTO bonus_category_amount_periods (bonus_category_id, amount, valid_from, note)
SELECT bc.id, bc.bonus_amount, DATE '1970-01-01', 'Preuzeto iz bonus_categories (V69).'
FROM bonus_categories bc
WHERE NOT EXISTS (
    SELECT 1 FROM bonus_category_amount_periods p
    WHERE p.bonus_category_id = bc.id
);

-- =============================================================================
-- The administration has a daily roster
-- =============================================================================
-- WHAT CHANGES
--   One new table, admin_schedule_entries: which shift an ADMINISTRATOR — a
--   sign-in account with the supervisor role, not a factory employee — works
--   on a given date. This is the first table that schedules app users;
--   work_shifts and the V50/V67 period tables stay employee-only and are not
--   touched.
--
--   The unit is the DAY, by the owner's decision:
--     · a person may hold more than one shift in a day (I then II);
--     · start_time/end_time, when set, narrow the assignment to a window
--       INSIDE the shift ("prva smena, ali samo prva 2h") — NULL means the
--       whole shift, whose hours stay the šifarnik's business (shifts row,
--       V50 defaults), never copied here.
--
-- WHAT READS IT
--   The new "Raspored administracije" screen under Podešavanja, behind the new
--   ADMIN_SCHEDULE_MANAGE capability (supervisor, admin, developer). Nothing
--   here decides pay — payroll reads work_shifts, and administrators are not
--   on kartoni.
--
-- AUDITABILITY
--   Rows are never hard-deleted: removal sets archived_at/archived_by, and the
--   audit triggers record every write like everywhere else.
--
--   · Rollback: DROP TABLE admin_schedule_entries;
--       DELETE FROM audit_tables WHERE table_name = 'admin_schedule_entries';
-- =============================================================================

CREATE TABLE admin_schedule_entries (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_date   date   NOT NULL,
    -- The administrator being scheduled — a users row, NOT an employee.
    user_id     bigint NOT NULL REFERENCES users (id),
    shift_id    bigint NOT NULL REFERENCES shifts (id),
    -- NULL pair = the whole shift; a set pair = a window inside it.
    start_time  time,
    end_time    time,
    note        varchar(255),
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    archived_at timestamptz,
    archived_by bigint REFERENCES users (id),
    -- A window has both ends or neither.
    CONSTRAINT chk_ase_window_pair CHECK ((start_time IS NULL) = (end_time IS NULL)),
    -- end < start is legal (a window across midnight, shift III); equal is not.
    CONSTRAINT chk_ase_times_differ CHECK (start_time IS NULL OR start_time <> end_time)
);

COMMENT ON TABLE admin_schedule_entries IS
    'Which shift an administrator (a supervisor-role USER, not an employee) works on a date. More than one row per person per day is legal; start/end times, when set, narrow the row to a window inside the shift. Removal archives, never deletes.';
COMMENT ON COLUMN admin_schedule_entries.user_id IS
    'The scheduled administrator — references users, deliberately not employees.';
COMMENT ON COLUMN admin_schedule_entries.start_time IS
    'NULL = the whole shift (its hours stay in the šifarnik); set = this window inside it.';

-- One FULL-shift row per (day, person, shift) — the only duplicate the data
-- model itself can name. Windowed rows may repeat (06–08 and 12–14 is a
-- legitimate day); the service refuses identical windows with a message.
CREATE UNIQUE INDEX ux_ase_full_shift
    ON admin_schedule_entries (work_date, user_id, shift_id)
    WHERE archived_at IS NULL AND start_time IS NULL;

CREATE INDEX idx_ase_date
    ON admin_schedule_entries (work_date)
    WHERE archived_at IS NULL;
CREATE INDEX idx_ase_user_date
    ON admin_schedule_entries (user_id, work_date)
    WHERE archived_at IS NULL;

CREATE TRIGGER trg_03_ase_updated_at
    BEFORE UPDATE ON admin_schedule_entries
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ── Auditing ─────────────────────────────────────────────────────────────────

INSERT INTO public.audit_tables (table_name)
SELECT 'admin_schedule_entries'
WHERE NOT EXISTS (
    SELECT 1 FROM public.audit_tables WHERE table_name = 'admin_schedule_entries'
);

DROP TRIGGER IF EXISTS trg_audit_logs_admin_schedule_entries
    ON public.admin_schedule_entries;
CREATE TRIGGER trg_audit_logs_admin_schedule_entries
    AFTER INSERT OR DELETE OR UPDATE ON public.admin_schedule_entries
    FOR EACH ROW EXECUTE FUNCTION public.audit_trigger_fn();

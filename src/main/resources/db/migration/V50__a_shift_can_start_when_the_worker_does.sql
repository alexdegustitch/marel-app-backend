-- ── Seed: today's defaults, restated as open-ended periods ───────────────────
-- valid_from is deliberately far in the past: the default period must cover
-- every date the app can ever be asked about, or the resolver would fall back
-- to the mutable shifts row for old kartone and history would drift with it.

INSERT INTO employee_shift_time_periods (shift_id, start_time, end_time, valid_from, note)
SELECT s.id, s.start_time, s.end_time, DATE '1970-01-01',
       'Podrazumevano vreme smene, preneto pri uvođenju istorije smena.'
FROM shifts s
WHERE NOT EXISTS (
    SELECT 1 FROM employee_shift_time_periods p
    WHERE p.shift_id = s.id AND p.employee_id IS NULL
);
